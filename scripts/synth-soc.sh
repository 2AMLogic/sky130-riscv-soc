#!/usr/bin/env bash
# Regenerate the synthesized soc_top gate-level netlist from a clean checkout.
#
#   scripts/synth-soc.sh
#
# fetch + hash-verify the pinned CVE2 sources and SRAM macro views, convert the
# core with sv2v, then run `klt synthesize` on flow/soc/synth_request.json
# (soc_top on sky130_fd_sc_hd, the SRAM macros black-boxed, the boot ROM built
# from firmware/soc/banner.hex). Writes the netlist to netlist/soc_top_synth.v
# and the klt result to $SYNTH_RESULT (default flow/build/soc_synth_result.json).
# Pre-route synthesis: no timing, and the macro area is not in area_um2.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
export PDK="${PDK:-sky130A}"
RESULT="${SYNTH_RESULT:-flow/build/soc_synth_result.json}"
mkdir -p "$(dirname "$RESULT")"

"$ROOT/scripts/fetch-cve2.sh"
"$ROOT/scripts/convert-cve2.sh"
"$ROOT/scripts/fetch-sram-macro.sh"

rm -rf flow/soc/.klt
klt synthesize flow/soc/synth_request.json --format json > "$RESULT.tmp"
NETLIST="$(python3 -I - "$RESULT.tmp" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
if "error" in d:
    sys.exit("klt synthesize failed: " + d["error"]["message"])
print(d["netlist_path"]["path"])
PY
)"
mkdir -p netlist
cp "$NETLIST" netlist/soc_top_synth.v
mv "$RESULT.tmp" "$RESULT"
echo "ok    netlist/soc_top_synth.v sha256 $(sha256sum netlist/soc_top_synth.v | cut -d' ' -f1)"

# Record the digests of every source and of the netlist (flow/soc/synth.sha256), and
# write the T1 item-1 inventory. klt 0.8.0 has no `recorded` freshness record and a
# synthesized netlist has no byte-stable `klt ... --check`, so the inventory's freshness
# check is scripts/check-soc-netlist.py, which re-hashes these files (it does not
# re-synthesize; re-running this script and getting the same netlist hash does).
python3 -I - <<'PY'
import hashlib, json, pathlib

def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()

sources = sorted(str(p) for p in pathlib.Path("rtl").glob("*.sv")) + [
    "reuse.lock.json",
    "scripts/fetch-cve2.sh",
    "scripts/convert-cve2.sh",
    "scripts/fetch-sram-macro.sh",
    "scripts/synth-soc.sh",
    "flow/soc/synth_request.json",
    "firmware/soc/banner.hex",
]
NET = "netlist/soc_top_synth.v"
pathlib.Path("flow/soc/synth.sha256").write_text(
    "".join(f"{sha(p)}  {p}\n" for p in sources + [NET]))
inv = {
    "schema_version": 1,
    "kind": "t1-attestation-inventory",
    "t1_item": 1,
    "description": "soc_top RTL, the pinned CVE2 / SRAM-macro inputs (by hash in reuse.lock.json) and the klt synthesize request, plus the synthesized sky130_fd_sc_hd gate-level netlist. Regenerated by scripts/synth-soc.sh. Freshness: the sources and netlist still hash to flow/soc/synth.sha256 (recorded at synthesis). Pre-route synthesis: no timing claim; the SRAM macros are black boxes.",
    "sources": sources,
    "derived": [{
        "path": NET,
        "generator": "scripts/synth-soc.sh (klt synthesize flow/soc/synth_request.json)",
        "check": {"argv": ["python3", "-I", "scripts/check-soc-netlist.py"]},
    }],
}
pathlib.Path("attest").mkdir(exist_ok=True)
pathlib.Path("attest/item1.json").write_text(json.dumps(inv, indent=2) + "\n")
print("ok    flow/soc/synth.sha256, attest/item1.json")
PY
