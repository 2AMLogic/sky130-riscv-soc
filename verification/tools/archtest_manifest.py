#!/usr/bin/env python3
"""Turn an ACT4 build into what verification/tests/archtest/test_archtest.py loads.

    python3 -I archtest_manifest.py SELECTION.json WORKDIR OUTDIR LINK.LD REQUEST.json \\
                                  OBJCOPY LOCK.json SELECTION.txt

SELECTION.json is what archtest_select.py printed: the tests ACT4 selected for
the SoC and, for every other candidate, why not.  The tool first renders that
selection as a listing (OUTDIR/selection.txt) and requires it to equal the
committed SELECTION.txt (verification/tests/archtest/selection.txt): the
selected tests and the reason every other one is skipped belong to the pinned
riscv-arch-test commit and the SoC configuration in LOCK.json, not to a run,
so a build whose selection differs from the committed list stops until the
list is regenerated.

It then finds each selected test's ELF under WORKDIR/<config>/elfs, flattens
each to a binary image with the toolchain's objcopy and writes
OUTDIR/manifest.json: the test RAM's base and size (from LINK.LD), the result
block the tests halt with (dut/rvmodel_macros.h), and one entry per selected
test with its image, load address, entry point, signature range and the ELF's
sha256.  Fails, leaving no manifest, when a selected test has no ELF, when an
ELF is not linked for the RAM LINK.LD describes, or when REQUEST.json's ISRAM_AW
does not match that RAM's depth.  Images and manifest paths are relative to
OUTDIR, so the directory can be moved.
"""
import hashlib
import json
import re
import shutil
import struct
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

#: dut/rvmodel_macros.h: RVMODEL_HALT_PASS / RVMODEL_HALT_FAIL write li x1, <code>
#: to RVMODEL_HALT_ADDRESS, the first word of the D-SRAM.
HALT_WORD = 0
PASS_CODE = 123456789
FAIL_CODE = 1

IMPORT = "riscv-non-isa/riscv-arch-test"

ELF_HEADER = struct.Struct("<16s2H5I3H")  # ident, type, machine, version, entry, phoff, shoff, flags, ehsize, phentsize, phnum


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def locked_commit(lock):
    """The commit LOCK.json pins riscv-arch-test at."""
    imports = [i for i in json.loads(Path(lock).read_text())["imports"] if i["from"] == IMPORT]
    if len(imports) != 1:
        sys.exit(f"{lock}: expected one {IMPORT} import, found {len(imports)}")
    return imports[0]["commit"]


def count(n):
    return f"{n} test" if n == 1 else f"{n} tests"


def render_selection(selection, commit):
    """The selection as text: every selected test by name; every other
    candidate by name with its reasons, or by directory when all of its tests
    fail for the same reasons."""
    selected, deselected = selection["selected"], selection["deselected"]
    lines = [
        "# Tests riscv-arch-test selects for the sky130-riscv-soc, and why it rejects the rest.",
        "# Generated by scripts/build-archtest.sh from the pinned riscv-arch-test tree and",
        f"# verification/tests/archtest/dut/{selection['config']}.yaml: never edit it by hand.",
        f"riscv-arch-test commit: {commit}",
        "Implemented extensions: " + " ".join(selection["implemented_extensions"]),
        f"Candidates: {len(selected) + len(deselected)}   selected: {len(selected)}   deselected: {len(deselected)}",
        "",
        "## Selected",
        *selected,
        "",
        "## Deselected",
    ]
    by_dir = defaultdict(list)
    for entry in deselected:
        by_dir[entry["name"].rsplit("/", 1)[0]].append(entry)
    for directory, entries in sorted(by_dir.items()):
        groups = defaultdict(list)
        for entry in entries:
            groups[tuple(entry["reasons"])].append(entry["name"])
        if len(groups) == 1:
            # one line for a directory whose tests all fail alike
            (reasons, names), = groups.items()
            lines.append(f"{directory}/ ({count(len(names))}): {' ; '.join(reasons)}")
        else:
            # the largest group is the rest of the directory; the others test by test
            (reasons, names), = sorted(groups.items(), key=lambda item: -len(item[1]))[:1]
            lines.append(f"{directory}/ ({count(len(names))}, the rest of this directory): {' ; '.join(reasons)}")
            for other, other_names in sorted(groups.items()):
                if other != reasons:
                    lines += [f"{name}: {' ; '.join(other)}" for name in other_names]
    return "\n".join(lines) + "\n"


def linker_constants(link_script):
    """RAM_ORIGIN, RAM_LENGTH and TEST_BASE as integers, from the linker script's own lines."""
    text = Path(link_script).read_text()
    values = {}
    for name in ("RAM_ORIGIN", "RAM_LENGTH", "TEST_BASE"):
        match = re.findall(rf"^{name} = (0x[0-9A-Fa-f]+|\d+);", text, re.MULTILINE)
        if len(match) != 1:
            sys.exit(f"{link_script}: expected one '{name} = <value>;' line, found {len(match)}")
        values[name] = int(match[0], 0)
    return values["RAM_ORIGIN"], values["RAM_LENGTH"], values["TEST_BASE"]


def elf_loads(elf):
    """(entry, [(physical address, file offset, size)]) of an ELF32 little-endian executable."""
    data = Path(elf).read_bytes()
    ident, typ, machine, version, entry, phoff, shoff, flags, ehsize, phentsize, phnum = ELF_HEADER.unpack_from(data)
    if ident[:4] != b"\x7fELF" or ident[4] != 1 or ident[5] != 1 or typ != 2 or machine != 243:
        sys.exit(f"{elf}: not a little-endian ELF32 RISC-V executable")
    loads = []
    for i in range(phnum):
        p_type, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, _flags, _align = struct.unpack_from("<8I", data, phoff + i * phentsize)
        if p_type == 1:  # PT_LOAD
            loads.append((p_paddr, p_offset, p_filesz))
    return entry, loads


def signature_range(nm, elf):
    """[begin_signature, end_signature): where ACT4 keeps the reference results
    the self-check compares against, from the ELF's symbol table."""
    symbols = subprocess.run([nm, str(elf)], check=True, capture_output=True, text=True).stdout.splitlines()
    addresses = {}
    for line in symbols:
        fields = line.split()
        if len(fields) == 3 and fields[2] in ("begin_signature", "end_signature"):
            addresses[fields[2]] = int(fields[0], 16)
    if set(addresses) != {"begin_signature", "end_signature"} or addresses["begin_signature"] >= addresses["end_signature"]:
        sys.exit(f"{elf}: no begin_signature/end_signature symbols")
    return [addresses["begin_signature"], addresses["end_signature"]]


def main():
    if len(sys.argv) != 9:
        print(__doc__.split("\n\n", 1)[1].strip(), file=sys.stderr)
        return 2
    selection_file, workdir, outdir, link_script, request, objcopy, lock, committed = (Path(a) for a in sys.argv[1:])
    nm = str(objcopy).replace("objcopy", "nm")  # the toolchain names its binutils alike (act does the same)
    selection = json.loads(selection_file.read_text())
    commit = locked_commit(lock)

    # The selection belongs to the pin and the configuration: it has to be the
    # committed one before anything is built from it.
    listing = render_selection(selection, commit)
    (outdir / "selection.txt").write_text(listing)
    if not committed.is_file() or committed.read_text() != listing:
        sys.exit(
            f"{committed} does not list what riscv-arch-test {commit[:7]} selects for {selection['config']} "
            f"(differs, or is missing): the pin or the configuration moved; regenerate it with\n"
            f"  cp {outdir / 'selection.txt'} {committed}"
        )

    ram_base, ram_bytes, test_base = linker_constants(link_script)
    ram_words = ram_bytes // 4
    if ram_bytes % 4 or ram_words & (ram_words - 1):
        sys.exit(f"{link_script}: RAM_LENGTH {ram_bytes:#x} is not a power-of-two number of words")

    parameters = json.loads(request.read_text()).get("parameters", {})
    aw = ram_words.bit_length() - 1
    if parameters.get("ISRAM_AW") != aw:
        sys.exit(f"{request}: parameters.ISRAM_AW is {parameters.get('ISRAM_AW')}, but {link_script} describes a {ram_words}-word RAM (ISRAM_AW {aw})")

    config = selection["config"]
    elfs = workdir / config / "elfs"
    images = outdir / "images"
    if images.exists():
        shutil.rmtree(images)
    tests = []
    for name in selection["selected"]:
        elf = elfs / Path(name).with_suffix(".elf")  # act names an ELF after the test's source without .S
        if not elf.is_file():
            sys.exit(f"{elf}: selected test was not built")
        entry, loads = elf_loads(elf)
        if entry != test_base:
            sys.exit(f"{elf}: entry point {entry:#x} is not TEST_BASE {test_base:#x}; the boot ROM would jump past it")
        if any(addr < ram_base or addr + size > ram_base + ram_bytes for addr, _, size in loads):
            sys.exit(f"{elf}: a loadable segment lies outside the test RAM {ram_base:#x}..{ram_base + ram_bytes:#x}")
        load_address = min(addr for addr, _, _ in loads)
        image = images / Path(name).with_suffix(".bin")
        image.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([objcopy, "-O", "binary", str(elf), str(image)], check=True)
        data = image.read_bytes()
        if len(data) % 4 or load_address % 4:
            sys.exit(f"{elf}: image is not word-aligned")
        first_offset = next(offset for addr, offset, _ in loads if addr == load_address)
        if data[:4] != elf.read_bytes()[first_offset:first_offset + 4]:
            sys.exit(f"{elf}: objcopy's first word does not sit at the lowest load address {load_address:#x}")
        signature = signature_range(nm, elf)
        if not load_address <= signature[0] <= signature[1] <= load_address + len(data):
            sys.exit(f"{elf}: signature {signature} is outside the image")
        tests.append(
            {
                "name": name,
                "image": str(image.relative_to(outdir)),
                "load_address": load_address,
                "entry": entry,
                "elf": str(elf.relative_to(outdir)),
                "elf_sha256": sha256(elf),
                "signature": signature,
            }
        )
    built = sorted(str(p.relative_to(elfs).with_suffix(".S")) for p in elfs.rglob("*.elf"))
    if built != sorted(selection["selected"]):
        sys.exit(f"{elfs}: holds {len(built)} ELFs, the selection names {len(selection['selected'])}")

    manifest = {
        "schema": 1,
        "config": config,
        "riscv_arch_test": commit,
        "ram": {"base": ram_base, "words": ram_words, "aw": aw},
        "halt": {"word": HALT_WORD, "pass_code": PASS_CODE, "fail_code": FAIL_CODE},
        "tests": tests,
    }
    (outdir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(f"ok    {len(tests)} test images in {images.relative_to(outdir)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
